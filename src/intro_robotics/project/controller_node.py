"""Live ROS mode: the supplied node that runs your Controller class.

    ros2 launch homework/project/project.launch.py scenario:=s2 \\
        controller:=homework.project.my_controller:MyController

You do not edit this file. It subscribes to both camera images, the joint
state, and the pickup actuator's state; when all four carry the same
simulated-time stamp, it builds the same Observation the graded runner
builds, calls your controller's step(), and publishes the Command as a
joint-velocity command and a pickup request. Your class never touches ROS
types, so the file you test offline is the file that runs here.

Topics (relative names; the launch file puts them under /project):

    fixed_camera/image_raw, tool_camera/image_raw   sensor_msgs/Image (subscribed)
    joint_states                                    sensor_msgs/JointState (subscribed)
    actuator/state                                  conveyor_interfaces/PickupState (subscribed)
    joint_velocity_command                          std_msgs/Float64MultiArray
    actuator/request                                conveyor_interfaces/PickupRequest
"""

import argparse
from importlib import import_module
import sys
import time as wallclock
import traceback

import numpy as np

from . import ros_bridge
from .contract import Command, Observation
from .scenario import load_scenario, make_task

PARTS = ("fixed", "tool", "joints", "actuator")


def load_class(spec):
    module, _, name = spec.partition(":")
    return getattr(import_module(module), name)


class ObservationAssembler:
    """Collects the four messages of one control period, matched by stamp.

    add(stamp_ns, part, value) returns the complete parts dict once all four
    have arrived for a stamp newer than the last one returned, else None.
    Older, incomplete periods are dropped.
    """

    def __init__(self):
        self.waiting, self.last = {}, -1

    def add(self, stamp, part, value):
        if stamp <= self.last:
            return None
        parts = self.waiting.setdefault(stamp, {})
        parts[part] = value
        if len(parts) < len(PARTS):
            return None
        self.last = stamp
        self.waiting = {s: p for s, p in self.waiting.items() if s > stamp}
        return parts


def make_node(task, controller):
    """Build the controller node (rclpy must be initialized)."""
    from rclpy.node import Node
    from rclpy.parameter import Parameter
    from sensor_msgs.msg import Image, JointState
    from std_msgs.msg import Float64MultiArray

    from conveyor_interfaces.msg import PickupRequest, PickupState

    class ControllerNode(Node):
        def __init__(self):
            super().__init__("project_controller",
                             parameter_overrides=[Parameter("use_sim_time", value=True)])
            self.task, self.controller = task, controller
            self.assembler = ObservationAssembler()
            self.velocity = self.create_publisher(Float64MultiArray, "joint_velocity_command", 10)
            self.request = self.create_publisher(PickupRequest, "actuator/request", 10)
            self.create_subscription(Image, "fixed_camera/image_raw", lambda m: self.on_image(m, "fixed"), 2)
            self.create_subscription(Image, "tool_camera/image_raw", lambda m: self.on_image(m, "tool"), 2)
            self.create_subscription(JointState, "joint_states", self.on_joints, 10)
            self.create_subscription(PickupState, "actuator/state", self.on_actuator, 10)
            self.step_ms, self.failed = [], False
            self.controller.reset()
            self.get_logger().info(f"Running {type(controller).__name__}; waiting for the simulator")

        @staticmethod
        def nanoseconds(header):
            return header.stamp.sec * 1_000_000_000 + header.stamp.nanosec

        def on_image(self, message, part):
            image = ros_bridge.image_from_fields(message.height, message.width, message.encoding, message.data)
            self.offer(message.header, part, image)

        def on_joints(self, message):
            state = ros_bridge.arm_state_from_fields(message.name, message.position, message.velocity,
                                                     self.task.arm.n)
            self.offer(message.header, "joints", state)

        def on_actuator(self, message):
            self.offer(message.header, "actuator", message.phase)

        def offer(self, header, part, value):
            parts = self.assembler.add(self.nanoseconds(header), part, value)
            if parts is None:
                return
            q, dq = parts["joints"]
            obs = Observation(time=self.nanoseconds(header) / 1e9, fixed_image=parts["fixed"],
                              tool_image=parts["tool"], q=q, dq=dq, actuator=parts["actuator"])
            start = wallclock.perf_counter()
            try:
                command = self.controller.step(obs)
                if not isinstance(command, Command) or command.dq.shape != (self.task.arm.n,):
                    raise TypeError(f"step() must return a Command with {self.task.arm.n} joint velocities")
            except Exception:  # keep the graph alive; the arm holds still
                if not self.failed:
                    self.get_logger().error("Controller step() failed; sending zero velocity:\n"
                                            + traceback.format_exc())
                self.failed = True
                command = Command(np.zeros(self.task.arm.n))
            self.step_ms.append(1000 * (wallclock.perf_counter() - start))
            if len(self.step_ms) == 250:
                self.get_logger().info(f"step() takes {np.mean(self.step_ms):.1f} ms on average "
                                       f"(the control period is {1000 * self.task.control_period:.0f} ms)")
                self.step_ms = []
            self.velocity.publish(Float64MultiArray(data=[float(v) for v in command.dq]))
            request = PickupRequest(request=command.request)
            request.header = header
            self.request.publish(request)

    return ControllerNode()


def main(argv=None):
    import rclpy
    from rclpy.executors import ExternalShutdownException
    from rclpy.utilities import remove_ros_args

    argv = sys.argv if argv is None else argv
    parser = argparse.ArgumentParser(description="Run a project Controller as a ROS node")
    parser.add_argument("--scenario", default="s1")
    parser.add_argument("--controller", default="homework.project.my_controller:MyController")
    args = parser.parse_args(remove_ros_args(argv)[1:])
    task = make_task(load_scenario(args.scenario))
    controller = load_class(args.controller)(task)

    rclpy.init(args=argv)
    node = make_node(task, controller)
    try:
        rclpy.spin(node)
    except (KeyboardInterrupt, ExternalShutdownException):
        pass
    finally:
        node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()


if __name__ == "__main__":
    main()
